def generate(option, req):
    ids = [c["id"] for c in option["components"]]
    s = set(ids)
    fmt = dict(
        name=option["name"],
        sse="{ SSEAlgorithm: aws:kms, KMSMasterKeyID: !Ref DataKey }" if "kms" in s else "{ SSEAlgorithm: AES256 }",
        ddbsse="{ SSEEnabled: true, SSEType: KMS, KMSMasterKeyId: !Ref DataKey }" if "kms" in s else "{ SSEEnabled: true }",
        tracing="Active" if "xray" in s else "PassThrough",
        apitarget="      Target: !GetAtt ApiFunction.Arn\n" if "lambda" in s else "",
        alarmaction=("      Dimensions: [{ Name: FunctionName, Value: !Ref ApiFunction }]\n" if "lambda" in s else "")
        + ("      AlarmActions: [!Ref AlertsTopic]\n" if "sns" in s else ""),
    )
    out = [HEADER.format(name=option["name"], app=req["app_type"].replace('"', "'"), users=req["monthly_users"])]
    manual = [MANUAL[i] for i in ids if i in MANUAL]
    if manual:
        out.append("Metadata:\n  NextSteps:\n" + "".join(f"    - \"{m}\"\n" for m in manual))
    out.append("Resources:\n")
    order = ["kms", "s3_static", "s3_storage", "dynamodb", "sqs", "sns", "eventbridge", "cognito",
             "secrets_manager", "lambda", "apigw", "cloudwatch", "backup"]
    made = []
    for k in order:
        if k in s and not (k == "apigw" and "lambda" not in s):
            out.append(RES[k].format(**fmt))
            made.append(k)
    if "apigw" in made:
        out.append("""  ApiPermission:
    Type: AWS::Lambda::Permission
    Properties:
      Action: lambda:InvokeFunction
      FunctionName: !Ref ApiFunction
      Principal: apigateway.amazonaws.com
      SourceArn: !Sub 'arn:aws:execute-api:${AWS::Region}:${AWS::AccountId}:${HttpApi}/*/*'
""")
    if not made:   # template needs at least one resource
        out.append(RES["s3_storage"].format(**fmt))
    outs = []
    if "apigw" in made:
        outs.append("  ApiUrl:\n    Value: !GetAtt HttpApi.ApiEndpoint\n")
    if "cognito" in made:
        outs.append("  UserPoolId:\n    Value: !Ref UserPool\n")
    if "dynamodb" in made:
        outs.append("  TableName:\n    Value: !Ref AppTable\n")
    if outs:
        out.append("Outputs:\n" + "".join(outs))
    return "".join(out)
